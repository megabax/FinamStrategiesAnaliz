import re

def извлечь_сумму_из_строки(текст):
  """
  Извлекает числовую сумму из строки вида 'от 50 000 ₽'.

  Args:
    текст: Строка, которую нужно проанализировать.

  Returns:
    Целое число, представляющее сумму, или None, если строка не соответствует формату.
  """
  шаблон = r"от\s*([\d\s]+)\s*₽"  # Регулярное выражение
  результат = re.match(шаблон, текст)

  if результат:
    сумма_строкой = результат.group(1).replace(" ", "")  # Удаляем пробелы
    try:
      сумма = int(сумма_строкой)
      return сумма
    except ValueError:
      return None  # Если не удалось преобразовать в целое число
  else:
    return None  # Если строка не соответствует шаблону

# Примеры использования
строка1 = 'от 50 000 ₽'
строка2 = 'от 1 000 000 ₽'
строка3 = 'от 5000 ₽'
строка4 = 'Некорректная строка'
строка5 = 'от   123 456  ₽' # с лишними пробелами

сумма1 = извлечь_сумму_из_строки(строка1)
сумма2 = извлечь_сумму_из_строки(строка2)
сумма3 = извлечь_сумму_из_строки(строка3)
сумма4 = извлечь_сумму_из_строки(строка4)
сумма5 = извлечь_сумму_из_строки(строка5)

print(f"Строка: '{строка1}', Сумма: {сумма1}")
print(f"Строка: '{строка2}', Сумма: {сумма2}")
print(f"Строка: '{строка3}', Сумма: {сумма3}")
print(f"Строка: '{строка4}', Сумма: {сумма4}")
print(f"Строка: '{строка5}', Сумма: {сумма5}")

# Проверка типа
if сумма1 is not None:
  print(f"Тип суммы1: {type(сумма1)}") # Выведет <class 'int'>
